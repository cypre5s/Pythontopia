#!/usr/bin/env python3
"""Validate the production course-pack-43 files before starting Web services."""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any


EXPECTED_PDF_IDS = tuple(range(186, 193))
SHA256_HEX_LENGTH = 64
ALLOWED_REVIEW_STATUSES = {"machine_generated_unreviewed", "human_reviewed"}


class CourseDataValidationError(RuntimeError):
    pass


@dataclass(frozen=True)
class ValidationSummary:
    pdf_count: int
    video_count: int
    transcript_count: int
    segment_count: int


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise CourseDataValidationError(f"cannot read valid JSON: {path}") from exc


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise CourseDataValidationError(message)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def validate(root: Path, transcript_path: Path | None = None) -> ValidationSummary:
    root = root.resolve()
    _require(root.is_dir(), f"course data directory is missing: {root}")

    pdf_dir = root / "pdfs"
    for document_id in EXPECTED_PDF_IDS:
        pdf = pdf_dir / f"{document_id}.pdf"
        _require(
            pdf.is_file() and pdf.stat().st_size > 1024, f"missing/empty PDF: {pdf}"
        )

    manifest_path = root / "video_manifest.json"
    manifest = _load_json(manifest_path)
    _require(
        isinstance(manifest, list) and manifest,
        "video manifest must be a non-empty array",
    )
    videos: dict[int, dict[str, Any]] = {}
    video_paths: dict[int, Path] = {}
    for raw in manifest:
        _require(isinstance(raw, dict), "video manifest entry must be an object")
        video_id = raw.get("id")
        filename = str(raw.get("file") or "")
        object_id = str(raw.get("objectid") or "")
        _require(
            isinstance(video_id, int) and video_id > 0, "video id must be positive"
        )
        _require(video_id not in videos, f"duplicate video id: {video_id}")
        _require(
            filename == Path(filename).name and filename.endswith(".mp4"),
            f"unsafe video file: {filename}",
        )
        _require(bool(object_id), f"video {video_id} has no source object id")
        _require(
            isinstance(raw.get("durationSec"), int) and raw["durationSec"] > 0,
            f"video {video_id} has invalid duration",
        )
        video_path = (root / "videos" / filename).resolve()
        _require(
            video_path.parent == (root / "videos").resolve(),
            f"unsafe video path: {filename}",
        )
        _require(
            video_path.is_file() and video_path.stat().st_size > 1024,
            f"missing/empty video: {video_path}",
        )
        videos[video_id] = raw
        video_paths[video_id] = video_path

    corpus_path = (transcript_path or root / "video_transcripts.json").resolve()
    corpus = _load_json(corpus_path)
    _require(
        isinstance(corpus, dict) and corpus.get("schemaVersion") == 1,
        "unsupported transcript schema",
    )
    generator = corpus.get("generator")
    _require(isinstance(generator, dict), "transcript generator metadata is missing")
    _require(
        generator.get("engine") == "faster-whisper",
        "transcripts must be generated by faster-whisper",
    )
    _require(
        bool(generator.get("engineVersion")) and bool(generator.get("model")),
        "transcript generator version/model is missing",
    )
    _require(
        corpus.get("reviewStatus") in ALLOWED_REVIEW_STATUSES,
        "invalid transcript review status",
    )
    transcript_rows = corpus.get("videos")
    _require(
        isinstance(transcript_rows, list) and transcript_rows,
        "transcript videos must be a non-empty array",
    )

    transcripts: dict[int, dict[str, Any]] = {}
    segment_count = 0
    for row in transcript_rows:
        _require(isinstance(row, dict), "video transcript entry must be an object")
        video_id = row.get("videoId")
        _require(
            isinstance(video_id, int) and video_id in videos,
            f"unknown transcript video id: {video_id}",
        )
        _require(
            video_id not in transcripts, f"duplicate transcript video id: {video_id}"
        )
        source_sha = str(row.get("sourceSha256") or "")
        _require(
            len(source_sha) == SHA256_HEX_LENGTH
            and all(c in "0123456789abcdef" for c in source_sha),
            f"video {video_id} has invalid SHA-256",
        )
        _require(
            row.get("objectId") == videos[video_id]["objectid"],
            f"video {video_id} transcript object id is stale",
        )
        _require(
            row.get("sourceFile") == videos[video_id]["file"],
            f"video {video_id} transcript filename is stale",
        )
        _require(
            row.get("model") == generator["model"],
            f"video {video_id} transcript model is inconsistent",
        )
        _require(
            row.get("reviewStatus") in ALLOWED_REVIEW_STATUSES,
            f"video {video_id} has invalid review status",
        )
        _require(
            row.get("language") == "zh",
            f"video {video_id} transcript language must be zh",
        )
        _require(
            _sha256(video_paths[video_id]) == source_sha,
            f"video {video_id} SHA-256 does not match transcript",
        )

        segments = row.get("segments")
        _require(
            isinstance(segments, list) and segments,
            f"video {video_id} has no transcript segments",
        )
        previous_start = -1.0
        for segment in segments:
            _require(isinstance(segment, dict), f"video {video_id} segment is invalid")
            start = segment.get("startSec")
            end = segment.get("endSec")
            text = str(segment.get("text") or "").strip()
            _require(
                isinstance(start, (int, float)) and isinstance(end, (int, float)),
                f"video {video_id} segment timestamps are invalid",
            )
            _require(
                0 <= start < end and start >= previous_start,
                f"video {video_id} segments are unordered",
            )
            _require(bool(text), f"video {video_id} contains an empty segment")
            previous_start = float(start)
        segment_count += len(segments)
        transcripts[video_id] = row

    _require(
        set(transcripts) == set(videos),
        "transcript coverage does not exactly match video manifest",
    )
    return ValidationSummary(
        pdf_count=len(EXPECTED_PDF_IDS),
        video_count=len(videos),
        transcript_count=len(transcripts),
        segment_count=segment_count,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("course_data_dir", type=Path)
    parser.add_argument(
        "--transcript",
        type=Path,
        help="Validate this candidate transcript file against the course videos before installing it.",
    )
    args = parser.parse_args()
    try:
        summary = validate(args.course_data_dir, args.transcript)
    except CourseDataValidationError as exc:
        print(f"COURSE_RUNTIME_DATA_INVALID: {exc}")
        return 1
    print(
        "COURSE_RUNTIME_DATA_OK "
        f"pdfs={summary.pdf_count} videos={summary.video_count} "
        f"transcripts={summary.transcript_count} segments={summary.segment_count}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
