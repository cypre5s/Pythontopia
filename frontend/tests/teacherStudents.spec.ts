import { afterEach, expect, it, vi } from "vitest";
import { mount, flushPromises, type VueWrapper } from "@vue/test-utils";
import TeacherStudents from "../src/features/TeacherStudents.vue";
import { api } from "../src/shared/api";
let wrapper: VueWrapper | undefined;
afterEach(() => { wrapper?.unmount(); vi.restoreAllMocks(); });
it("paginates a large class and preserves selection across pages but clears it when filtering", async () => {
  vi.spyOn(api, "get").mockResolvedValue(Array.from({ length: 126 }, (_, i) => ({ id: i + 1, student_id: String(i).padStart(6, "0"), name: `学生${i}`, must_change_password: i % 2 === 0 })));
  wrapper = mount(TeacherStudents, { props: { classroomId: 1 } });
  await flushPromises();
  expect(wrapper.findAll("tbody tr")).toHaveLength(25);
  await wrapper.get('input[aria-label="选择本页学生"]').setValue(true);
  expect(wrapper.text()).toContain("重置密码（25）");
  await wrapper.get('button[aria-label="下一页学生"]').trigger("click");
  await wrapper.get('input[aria-label="选择本页学生"]').setValue(true);
  expect(wrapper.text()).toContain("重置密码（50）");
  await wrapper.get('input[type="search"]').setValue("000125");
  expect(wrapper.findAll("tbody tr")).toHaveLength(1);
  expect(wrapper.text()).toContain("学生125");
  expect(wrapper.find('[aria-label="批量操作"]').exists()).toBe(false);
  expect(wrapper.text()).toContain("第 1 / 1 页");
});
