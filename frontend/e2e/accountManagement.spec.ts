import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";

test("teacher provisions, imports, resets and removes students; temporary password must be changed", async ({ page, request }) => {
  test.setTimeout(120000);
  const teacherId = process.env.E2E_TEACHER_STUDENT_ID, teacherPassword = process.env.E2E_TEACHER_PASSWORD;
  test.skip(!teacherId || !teacherPassword, "Requires an isolated teacher account");
  const login = await request.post("/api/auth/login", { data: { student_id: teacherId, password: teacherPassword } });
  expect(login.ok()).toBeTruthy();
  const teacher = await login.json();
  const headers = { Authorization: `Bearer ${teacher.access_token}` };
  const classroomResponse = await request.post("/api/classrooms", { headers, data: { name: `账号管理验收 ${randomUUID().slice(0, 8)}` } });
  const classroom = await classroomResponse.json();
  await page.goto("/");
  await page.evaluate(token => sessionStorage.setItem("pythontopia-reborn-session", token), teacher.access_token);
  await page.goto("/teacher");
  await page.getByLabel("当前班级").selectOption(String(classroom.id));
  await page.getByRole("button", { name: "学生账号", exact: true }).click();
  const studentId = "00" + BigInt("0x" + randomUUID().replaceAll("-", "").slice(0, 12)).toString();
  await page.getByRole("button", { name: "按学号创建", exact: true }).click();
  const create = page.getByRole("dialog", { name: "创建学生账号", exact: true });
  await create.getByLabel("学号", { exact: true }).fill(studentId);
  await create.getByLabel("姓名", { exact: true }).fill("账号管理验收学生");
  await create.getByRole("button", { name: "创建账号", exact: true }).click();
  await expect(create).toBeHidden();
  await expect(page.getByRole("cell", { name: studentId, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "批量导入", exact: true }).click();
  const importer = page.getByRole("dialog", { name: "批量创建学生", exact: true });
  const importedId = studentId + "1";
  await importer.getByLabel("选择学生表格").setInputFiles({ name: "students.csv", mimeType: "text/csv", buffer: Buffer.from(`学号,姓名\n${importedId},导入验收学生\n`) });
  await expect(importer.getByRole("cell", { name: importedId, exact: true })).toBeVisible();
  await importer.getByRole("button", { name: "确认批量创建", exact: true }).click();
  await expect(importer).toBeHidden();
  await page.screenshot({ path: ".tmp-account-students.png", fullPage: true });

  await page.evaluate(() => sessionStorage.clear());
  await page.goto("/");
  await page.getByLabel("学号", { exact: true }).fill(studentId);
  await page.getByLabel("密码", { exact: true }).fill(studentId);
  await page.getByRole("button", { name: "进入小镇", exact: true }).click();
  await expect(page).toHaveURL(/change-password/);
  await page.reload();
  await expect(page.getByRole("heading", { name: "请先设置自己的密码" })).toBeVisible();
  const changedPassword = `Private-${randomUUID()}`;
  await page.getByLabel("当前密码", { exact: true }).fill(studentId);
  await page.getByLabel("新密码", { exact: true }).fill(changedPassword);
  await page.getByLabel("确认新密码", { exact: true }).fill(changedPassword);
  await page.getByRole("button", { name: "保存新密码", exact: true }).click();
  await expect(page).toHaveURL(/world/);
  const welcome = page.getByRole("dialog", { name: "欢迎回到小镇", exact: true });
  await welcome.getByRole("button", { name: "按任意键继续", exact: true }).click();
  await expect(welcome).toBeHidden();
  await page.locator(".hud-dock").getByRole("button", { name: "打开设置", exact: true }).click();
  await page.getByLabel("当前密码", { exact: true }).fill(changedPassword);
  const personalPassword = `Personal-${randomUUID()}`;
  await page.getByLabel("新密码", { exact: true }).fill(personalPassword);
  await page.getByLabel("确认新密码", { exact: true }).fill(personalPassword);
  await page.getByRole("button", { name: "保存新密码", exact: true }).click();
  await expect(page.getByText("密码已修改，其他设备的登录已失效。", { exact: true })).toBeVisible();
  await page.screenshot({ path: ".tmp-account-password.png", fullPage: true });
  const oldToken = await page.evaluate(() => sessionStorage.getItem("pythontopia-reborn-session"));

  await page.evaluate(token => sessionStorage.setItem("pythontopia-reborn-session", token), teacher.access_token);
  await page.goto("/teacher");
  await page.getByLabel("当前班级").selectOption(String(classroom.id));
  await page.getByRole("button", { name: "学生账号", exact: true }).click();
  await page.getByLabel(`选择${studentId}`, { exact: true }).check();
  await page.getByRole("button", { name: "重置密码（1）", exact: true }).click();
  await page.getByRole("dialog", { name: "重置学生密码" }).getByRole("button", { name: "确认操作" }).click();
  await expect(page.getByRole("dialog", { name: "重置学生密码" })).toBeHidden();
  expect((await request.get("/api/auth/me", { headers: { Authorization: `Bearer ${oldToken}` } })).status()).toBe(401);
  const resetLogin = await request.post("/api/auth/login", { data: { student_id: studentId, password: studentId } });
  expect((await resetLogin.json()).user.must_change_password).toBe(true);
  await page.getByLabel(`选择${importedId}`, { exact: true }).check();
  await page.getByRole("button", { name: "移出班级（1）", exact: true }).click();
  await page.getByRole("dialog", { name: "移出班级", exact: true }).getByRole("button", { name: "确认操作" }).click();
  await expect(page.getByRole("cell", { name: importedId, exact: true })).toHaveCount(0);
  expect((await request.post("/api/auth/login", { data: { student_id: importedId, password: importedId } })).ok()).toBeTruthy();
  await page.getByRole("button", { name: "我的密码", exact: true }).click();
  await expect(page.getByLabel("当前密码", { exact: true })).toBeVisible();
});
