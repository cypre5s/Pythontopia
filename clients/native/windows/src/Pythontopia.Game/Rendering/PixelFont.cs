        };

        var glyphs = new Dictionary<char, byte[]>(art.Count);
        foreach (var (ch, rows) in art)
        {
            var bytes = new byte[GlyphHeight];
            for (var y = 0; y < GlyphHeight; y++)
            {
                byte b = 0;
                var row = rows[y];
                for (var x = 0; x < GlyphWidth; x++)
                {
                    if (x < row.Length && row[x] == '#')
                    {
                        b |= (byte)(1 << (GlyphWidth - 1 - x));
                    }
                }

                bytes[y] = b;
            }

            glyphs[ch] = bytes;
        }

        return glyphs;
    }
}
