using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Pythontopia.Game.Rendering;

/// <summary>
/// A tiny self-contained 5x7 uppercase bitmap font drawn from a 1x1 white texture.
/// This avoids the MonoGame content pipeline (SpriteFont/.xnb) entirely so the game
/// builds from the WSL interop SDK and runs anywhere. Text is uppercased before
/// lookup; localized (CJK) labels are not rendered here by design — ASCII object
/// identifiers are used for the HUD and prompts instead.
/// </summary>
public sealed class PixelFont
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;
    private const int Advance = GlyphWidth + 1;

    private readonly Texture2D _pixel;
    private static readonly Dictionary<char, byte[]> Glyphs = BuildGlyphs();

    public PixelFont(Texture2D pixel) => _pixel = pixel;

    public int LineHeight(int scale) => GlyphHeight * scale;

    public int Measure(string text, int scale) => text.Length * Advance * scale;

    public void Draw(SpriteBatch batch, string text, Vector2 position, Color color, int scale = 2)
    {
        var cursorX = (int)position.X;
        var baseY = (int)position.Y;

        foreach (var raw in text)
        {
            var c = char.ToUpperInvariant(raw);
            if (c != ' ')
            {
                if (!Glyphs.TryGetValue(c, out var rows))
                {
                    rows = Glyphs['?'];
                }

                for (var y = 0; y < GlyphHeight; y++)
                {
                    var bits = rows[y];
                    for (var x = 0; x < GlyphWidth; x++)
                    {
                        if ((bits & (1 << (GlyphWidth - 1 - x))) != 0)
                        {
                            batch.Draw(
                                _pixel,
                                new Rectangle(cursorX + x * scale, baseY + y * scale, scale, scale),
                                color);
                        }
                    }
                }
            }

            cursorX += Advance * scale;
        }
    }

    private static Dictionary<char, byte[]> BuildGlyphs()
    {
        var art = new Dictionary<char, string[]>
        {
            ['A'] = new[] { ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#" },
            ['B'] = new[] { "####.", "#...#", "#...#", "####.", "#...#", "#...#", "####." },
